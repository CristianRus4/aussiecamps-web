/**
 * Writes places-worker/src/symbols.js: the icon of each SF Symbol a live link may carry ("sym"), drawn with
 * the closest icon of the site's own set (lucide). The Worker can't load lucide, so the table holds each icon's
 * SVG markup. tests/live-links.test.mjs checks the file matches; after a lucide update or a new symbol:
 *
 *   npm run links:symbols
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
export const SYMBOLS_FILE = resolve(root, "places-worker/src/symbols.js");

/** The app's symbols and their lucide icons. */
export const SYMBOL_ICONS = {
  "folder.fill": "folder", "star.fill": "star", "heart.fill": "heart", "bookmark.fill": "bookmark", "tent.fill": "tent",
  "house.lodge.fill": "house", "car.side.fill": "car", "bus.fill": "bus", "mountain.2.fill": "mountain", "water.waves": "waves-horizontal",
  "beach.umbrella.fill": "umbrella", "tree.fill": "tree-deciduous", "leaf.fill": "leaf", "sun.max.fill": "sun",
  "moon.stars.fill": "moon-star", "snowflake": "snowflake", "figure.hiking": "footprints", "figure.surfing": "waves-horizontal",
  "bicycle": "bike", "sailboat.fill": "sailboat", "fork.knife": "utensils", "flame.fill": "flame", "binoculars.fill": "binoculars",
  "camera.fill": "camera", "pawprint.fill": "paw-print", "fish.fill": "fish", "bird.fill": "bird", "map.fill": "map",
  "backpack.fill": "backpack", "cup.and.saucer.fill": "coffee", "car.fill": "car",
};

const attribute = (value) => String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;");

async function iconMarkup(name) {
  const file = resolve(root, `node_modules/lucide-react/dist/esm/icons/${name}.mjs`);
  const { __iconNode } = await import(pathToFileURL(file).href);
  return __iconNode.map(([tag, attrs]) => `<${tag}${Object.entries(attrs).filter(([key]) => key !== "key").map(([key, value]) => ` ${key}="${attribute(value)}"`).join("")}/>`).join("");
}

export async function symbolsSource() {
  const lines = [];
  for (const [symbol, icon] of Object.entries(SYMBOL_ICONS)) lines.push(`  ${JSON.stringify(symbol)}: ${JSON.stringify(await iconMarkup(icon))}, // ${icon}`);
  return `// Generated by scripts/link-symbols.mjs from lucide-react: the inside of a 24 × 24 stroke icon per SF Symbol.
export const SYMBOLS = {
${lines.join("\n")}
};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const source = await symbolsSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(SYMBOLS_FILE, "utf8") !== source) { console.error("places-worker/src/symbols.js is out of date: run npm run links:symbols"); process.exit(1); }
  } else {
    writeFileSync(SYMBOLS_FILE, source);
    console.log(`Wrote ${Object.keys(SYMBOL_ICONS).length} symbols to places-worker/src/symbols.js.`);
  }
}
