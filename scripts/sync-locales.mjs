#!/usr/bin/env node
/**
 * Keeps everything that lists the site's languages in step with lib/locales.json.
 *
 * The registry is the one place a language is declared. This script writes what cannot read JSON at
 * the right moment:
 *
 * - lib/translations/index.ts: the static import barrel for every locale file. Bundlers need static
 *   imports, so the list of JSON files is generated rather than built at runtime.
 * - docs/translation.config.json: the translation engine's `locales`, `targets` and `varieties`.
 *
 *   npm run locales:sync            write both files
 *   npm run locales:sync -- --check exit 1 if either is stale (part of npm run content:check)
 *
 * Draft locales are included in both: their translators need targets before the locale goes live.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const registry = JSON.parse(readFileSync(resolve(root, "lib/locales.json"), "utf8"));

const fields = ["code", "segment", "label", "htmlLang", "hreflang", "og", "intl", "engine", "script", "status", "reviews"];
const problems = [];
const seen = new Set();
for (const entry of registry) {
  const missing = fields.filter((field) => entry[field] === undefined || entry[field] === "" || entry[field] === null);
  if (missing.length) problems.push(`${entry.code ?? "?"}: missing ${missing.join(", ")}`);
  if (Object.keys(entry).some((key) => !fields.includes(key))) problems.push(`${entry.code}: unknown field`);
  if (!/^[a-z]{2}(?:-[a-z]+)?$/.test(entry.code)) problems.push(`${entry.code}: code must be lowercase BCP 47 (de, zh-hans)`);
  if (!/^[a-z]{2}(?:-[a-z]+)?$/.test(entry.segment)) problems.push(`${entry.code}: bad URL segment ${entry.segment}`);
  if (!Array.isArray(entry.hreflang) || !entry.hreflang.length) problems.push(`${entry.code}: hreflang must be a non-empty list`);
  if (!["latin", "cjk"].includes(entry.script)) problems.push(`${entry.code}: script must be latin or cjk`);
  if (!["live", "draft"].includes(entry.status)) problems.push(`${entry.code}: status must be live or draft`);
  if (typeof entry.reviews !== "boolean") problems.push(`${entry.code}: reviews must be true or false`);
  if (!/^[a-z]{2}_[A-Z]{2}$/.test(entry.og)) problems.push(`${entry.code}: og must look like de_DE`);
  for (const key of [`code:${entry.code}`, `segment:${entry.segment}`]) {
    if (seen.has(key)) problems.push(`duplicate ${key}`);
    seen.add(key);
  }
  if (!existsSync(resolve(root, `lib/translations/${entry.code}.json`))) problems.push(`${entry.code}: lib/translations/${entry.code}.json does not exist`);
}
if (problems.length) {
  console.error(`lib/locales.json is invalid:\n- ${problems.join("\n- ")}`);
  process.exit(1);
}

const identifier = (code) => code.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
const key = (code) => (/^[a-z]+$/.test(code) ? code : JSON.stringify(code));
const barrel = `// Generated by \`npm run locales:sync\` from lib/locales.json. Do not edit by hand.
${registry.map(({ code }) => `import ${identifier(code)} from "./${code}.json";`).join("\n")}

/** Every locale in the registry, live or draft, in registry order. */
export const localeCodes = [${registry.map(({ code }) => JSON.stringify(code)).join(", ")}] as const;
export type LocaleCode = (typeof localeCodes)[number];

/** The raw translation file for each locale. lib/localized.ts decides what is complete enough to use. */
export const translationFiles: Record<LocaleCode, unknown> = { ${registry.map(({ code }) => `${key(code)}: ${identifier(code)}`).join(", ")} };
`;

const configPath = resolve(root, "docs/translation.config.json");
const config = JSON.parse(readFileSync(configPath, "utf8"));
const catalog = config.catalogs.find((item) => item.adapter === "web-json");
catalog.locales = registry.map(({ code }) => code);
catalog.targets = registry.map(({ code }) => ({ locale: code, path: `../lib/translations/${code}.json` }));
const varieties = Object.fromEntries(registry.filter(({ code, engine }) => engine !== code).map(({ code, engine }) => [code, engine]));
if (Object.keys(varieties).length) catalog.varieties = varieties;
else delete catalog.varieties;
const configText = `${JSON.stringify(config, null, 2)}\n`;

const outputs = [[resolve(root, "lib/translations/index.ts"), barrel], [configPath, configText]];
const stale = outputs.filter(([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text);
if (check) {
  if (stale.length) {
    console.error(`Stale locale files, run \`npm run locales:sync\`: ${stale.map(([path]) => path.replace(`${root}/`, "")).join(", ")}`);
    process.exit(1);
  }
  console.log(`Locales in sync: ${registry.map(({ code, status }) => `${code}${status === "draft" ? " (draft)" : ""}`).join(", ")}`);
} else {
  for (const [path, text] of stale) writeFileSync(path, text);
  console.log(`locales:sync wrote ${stale.length} file(s) for ${registry.length} locales`);
}
